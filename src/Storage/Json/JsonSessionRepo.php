<?php

declare(strict_types=1);

namespace WPSafeMode\Storage\Json;

use WPSafeMode\Storage\Contracts\SessionRepo;
use WPSafeMode\Storage\Contracts\StorageException;
use WPSafeMode\Storage\Session;

/**
 * One directory per session (spec 7.2). The session record itself lives in
 * session.php; Task 5 adds messages.php beside it.
 */
final class JsonSessionRepo implements SessionRepo
{
    public function __construct(private string $baseDir)
    {
    }

    public function create(Session $session): void
    {
        if ($this->find($session->id) !== null) {
            throw new StorageException('Session already exists: ' . $session->id);
        }

        $this->fileFor($session->id)->write($session->toRow());
    }

    public function find(string $id): ?Session
    {
        $path = $this->pathFor($id);

        if (!is_file($path)) {
            return null;
        }

        $row = (new JsonFile($path))->read();

        return $row === [] ? null : Session::fromRow($row);
    }

    public function update(Session $session): void
    {
        if ($this->find($session->id) === null) {
            throw new StorageException('Unknown session: ' . $session->id);
        }

        $this->fileFor($session->id)->write($session->toRow());
    }

    public function list(int $limit = 50): array
    {
        if (!is_dir($this->baseDir)) {
            return [];
        }

        $sessions = [];

        foreach (scandir($this->baseDir) ?: [] as $entry) {
            if ($entry === '.' || $entry === '..') {
                continue;
            }

            $session = $this->find($entry);

            if ($session !== null) {
                $sessions[] = $session;
            }
        }

        usort(
            $sessions,
            static fn (Session $a, Session $b): int
                => [$b->createdAt, $b->id] <=> [$a->createdAt, $a->id]
        );

        return array_slice($sessions, 0, $limit);
    }

    public function delete(string $id): void
    {
        $path = $this->pathFor($id);

        if (is_file($path)) {
            unlink($path);
        }

        $dir = dirname($path);

        if (is_dir($dir) && (scandir($dir) ?: []) === ['.', '..']) {
            rmdir($dir);
        }
    }

    private function fileFor(string $id): JsonFile
    {
        return new JsonFile($this->pathFor($id));
    }

    /**
     * Session ids are generated by us, never supplied by a user or the model,
     * but this method is the boundary where an id becomes a filesystem path,
     * so it validates rather than trusts (spec 5.6).
     */
    private function pathFor(string $id): string
    {
        if (preg_match('/^[A-Za-z0-9_-]{1,64}$/', $id) !== 1) {
            throw new StorageException('Illegal session id: ' . $id);
        }

        return $this->baseDir . '/' . $id . '/session.php';
    }
}
